import assert from 'node:assert/strict';
import {clusters} from '../dist/data.js';
import {gpuMemoryGB,matchingParts,researchAccess,cpuArchitecture} from '../dist/discovery.js';
const perlmutter=clusters.find(c=>c.id==='perlmutter');
assert.deepEqual(matchingParts(perlmutter,{memory:'80'}).map(x=>x.index),[1]);
assert.equal(matchingParts(perlmutter,{memory:'80',model:'CPU only'}).length,0);
assert.equal(gpuMemoryGB({vram:'80 / 96 GB (operator listing)'}),null);
assert.equal(gpuMemoryGB({vram:'1.5 TB HBM3 across 16 chips'}),null);
assert.equal(gpuMemoryGB({vram:'128 GB per GPU',apu:true}),null);
assert.equal(gpuMemoryGB({vram:'32 GB per GPU',mixed:true}),null);
assert.equal(gpuMemoryGB({gpu:'AMD MI250X',vram:'128 GB per physical accelerator'}),null);
assert.equal(gpuMemoryGB({vram:'40 GiB per GPU'}),40*2**30/1e9);
assert.equal(cpuArchitecture({cpu:'Host CPU model not verified · 192 vCPUs'}),null);
assert.equal(matchingParts(clusters.find(c=>c.id==='stargate-abilene'),{access:'research'}).length,0);
const split={id:'split',network:'InfiniBand',parts:[{cpu:'AMD EPYC',gpu:'A100',gpus:4,vram:'40 GB per GPU'},{cpu:'NVIDIA Grace',gpu:'H100',gpus:4,vram:'96 GB per GPU'}]};
assert.equal(matchingParts(split,{cpu:'x86-64',memory:'80'}).length,0);
assert.equal(Object.keys(researchAccess).length,7);
for(const id of Object.keys(researchAccess))assert.ok(clusters.some(c=>c.id===id));
console.log('PASS discovery filtering: same-node requirements, exact memory, unknowns, shared memory, access routes.');
